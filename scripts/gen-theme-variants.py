"""Generates components/themeVariantStyles.ts: CSS that recolors the Marcel-based Cozy style
and the Dragon-based Spooky style. Run after changing theme colors in components:
    python3 scripts/gen-theme-variants.py
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

_ts = (ROOT / 'utils/themeVariants.ts').read_text(encoding='utf-8')
import json as _json
_pal = _json.loads(_ts.split('= ', 1)[0] and _ts[_ts.index('/*palette-start*/'):_ts.index('/*palette-end*/')].split('= ', 1)[1].rstrip().rstrip(';'))
VARIANTS = {
    # name: (root class, base root class, {base hex: new hex}); colors live in utils/themeVariants.ts
    'cozy': ('cozy-mode', 'marcel-mode', _pal['Cozy']),
    'spooky': ('spooky-mode', 'dragon-mode', _pal['Spooky']),
}

PROPS = {
    'bg': 'background-color', 'text': 'color', 'border': 'border-color',
    'border-t': 'border-top-color', 'border-b': 'border-bottom-color',
    'border-l': 'border-left-color', 'border-r': 'border-right-color',
    'border-x': 'border-left-color', 'border-y': 'border-top-color',
    'ring': '--tw-ring-color', 'fill': 'fill', 'stroke': 'stroke', 'outline': 'outline-color',
    'accent': 'accent-color', 'caret': 'caret-color', 'decoration': 'text-decoration-color',
    'from': '--tw-gradient-from', 'to': '--tw-gradient-to', 'divide': 'border-color',
}
PSEUDO = {'hover': ':hover', 'focus': ':focus', 'active': ':active', 'disabled': ':disabled',
          'placeholder': '::placeholder', 'focus-within': ':focus-within', 'first': ':first-child', 'last': ':last-child'}

TOKEN = re.compile(r'(?<![\w\-\[])((?:[a-z\-]+:)*)(bg|text|border(?:-[tblrxy])?|ring|fill|stroke|outline|accent|caret|decoration|from|to|divide)-\[#([0-9a-fA-F]{6})\](?:/(\d{1,3}))?')

def esc(cls):
    return re.sub(r'([:\[\]#/.%()])', r'\\\1', cls)

def rgba(hexv, alpha):
    r, g, b = (int(hexv[i:i+2], 16) for i in (0, 2, 4))
    return f'rgba({r}, {g}, {b}, {alpha})' if alpha is not None else f'#{hexv}'

night = []
def build(root, base, table):
    lower = {k.lower(): v for k, v in table.items()}
    rules, seen, skipped = [], set(), set()
    for f in list(ROOT.glob('components/*.tsx')) + [ROOT / 'App.tsx']:
        for m in TOKEN.finditer(f.read_text(encoding='utf-8')):
            variants, prop, hexv, op = m.group(1), m.group(2), m.group(3), m.group(4)
            new = lower.get(hexv.lower())
            if not new or m.group(0) in seen:
                continue
            seen.add(m.group(0))
            sel_suffix, media, prefix = '', None, ''
            ok = True
            for v in [x for x in variants.split(':') if x]:
                if v in PSEUDO: sel_suffix += PSEUDO[v]
                elif v == 'group-hover': prefix = '.group:hover '
                elif v == 'dark': media = '(prefers-color-scheme: dark)'
                elif v in ('sm', 'md', 'lg', 'xl'): media = {'sm': '(min-width: 640px)', 'md': '(min-width: 768px)', 'lg': '(min-width: 1024px)', 'xl': '(min-width: 1280px)'}[v]
                else: ok = False
            if not ok:
                skipped.add(m.group(0)); continue
            value = rgba(new, int(op) / 100 if op else None)
            decl = f'{PROPS[prop]}: {value} !important;'
            if prop == 'divide':
                rule = f'.{root} {prefix}.{esc(m.group(0))}{sel_suffix} > * + * {{ {decl} }}'
            else:
                rule = f'.{root} {prefix}.{esc(m.group(0))}{sel_suffix} {{ {decl} }}'
            rules.append(f'@media {media} {{ {rule} }}' if media else rule)
    # Recolor the base style's own CSS blocks in AppStyles the same way
    styles = (ROOT / 'components/AppStyles.tsx').read_text(encoding='utf-8')
    flag = {'dragon-mode': ['isDragon'], 'marcel-mode': ['isMarcel']}[base]
    for fl in flag:
        m = re.search(r'\{' + fl + r' && \(\s*<style>\{`(.*?)`\}</style>', styles, re.S)
        css = m.group(1).replace('\\\\', '\\')
        css = css.replace('.' + base, '.' + base + '.' + root)
        def hexsub(mm):
            new = lower.get(mm.group(1).lower())
            return '#' + new if new else mm.group(0)
        css = re.sub(r'(?<!\\)#([0-9a-fA-F]{6})\b', hexsub, css)
        rgbmap = {tuple(int(k[i:i+2], 16) for i in (0, 2, 4)): v for k, v in lower.items()}
        def rgbsub(mm):
            key = tuple(int(x) for x in mm.group(1, 2, 3))
            if key not in rgbmap: return mm.group(0)
            v = rgbmap[key]; r, g, b = (int(v[i:i+2], 16) for i in (0, 2, 4))
            return f'rgba({r}, {g}, {b}, {mm.group(4)})'
        css = re.sub(r'rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)', rgbsub, css)
        if fl == 'isDarkMarcel':
            css = '/* night */\n' + css
            night.append(css)
        else:
            rules.insert(0, css)
    return rules, skipped

out = ['// Generated by scripts/gen-theme-variants.py. Do not edit by hand.', '']
for name, (root, base, table) in VARIANTS.items():
    rules, skipped = build(root, base, table)
    if skipped: print(name, 'skipped:', sorted(skipped))
    print(name, len(rules), 'rules')
    body = '\n'.join(rules)
    out.append(f'export const {name}Css = String.raw`\n{body}\n`;\n')

(ROOT / 'components/themeVariantStyles.ts').write_text('\n'.join(out), encoding='utf-8')
